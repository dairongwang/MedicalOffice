#!/usr/bin/env python3
"""Development server for the staff dashboard (plain static files, no build step).

    python serve.py --port 4300 --api http://localhost:8000

Serves this folder over HTTP and answers ``config.js`` dynamically so the dashboard knows where
the API lives (``window.STAFF_CONFIG``). ``python dev.py run`` starts it on its own origin next
to the API and the main app. Standard library only; never used in production (the Dockerfile
puts the same files behind nginx and the container entrypoint writes config.js instead).
"""

from __future__ import annotations

import argparse
import sys
from functools import partial
from http.server import SimpleHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path

HERE = Path(__file__).resolve().parent
CONFIG_GLOBAL = "STAFF_CONFIG"


class Handler(SimpleHTTPRequestHandler):
    """Static files from this folder + a generated config.js; nothing is cached."""

    api_base = ""
    show_dummy_hint = True

    def __init__(self, *args, **kwargs):
        super().__init__(*args, directory=str(HERE), **kwargs)

    def do_GET(self):  # noqa: N802 - http.server naming
        if self.path.split("?", 1)[0] == "/config.js":
            body = (
                f"// Generated by serve.py\nwindow.{CONFIG_GLOBAL} = "
                f'{{ apiBase: "{self.api_base}", showDummyHint: {"true" if self.show_dummy_hint else "false"} }};\n'
            ).encode()
            self.send_response(200)
            self.send_header("Content-Type", "application/javascript; charset=utf-8")
            self.send_header("Content-Length", str(len(body)))
            self.send_header("Cache-Control", "no-store")
            self.end_headers()
            self.wfile.write(body)
            return
        super().do_GET()

    def end_headers(self):
        self.send_header("Cache-Control", "no-cache")
        self.send_header("X-Content-Type-Options", "nosniff")
        self.send_header("X-Frame-Options", "DENY")
        super().end_headers()

    def log_message(self, fmt, *args):  # quieter than the default (one line per file)
        if "config.js" in (args[0] if args else ""):
            return
        sys.stderr.write("[staff] " + fmt % args + "\n")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--port", type=int, default=4300)
    parser.add_argument("--host", default="127.0.0.1")
    parser.add_argument("--api", default="http://localhost:8000", help="origin of the Medic Office API")
    parser.add_argument("--no-dummy-hint", action="store_true", help="hide the dummy sign-in credentials")
    args = parser.parse_args(argv)

    handler = partial(Handler)
    Handler.api_base = args.api.rstrip("/")
    Handler.show_dummy_hint = not args.no_dummy_hint
    Handler.extensions_map.update({".js": "application/javascript", ".mjs": "application/javascript"})
    server = ThreadingHTTPServer((args.host, args.port), handler)
    print(f"Staff dashboard: http://localhost:{args.port}/   (API: {Handler.api_base})", flush=True)
    try:
        server.serve_forever()
    except KeyboardInterrupt:
        pass
    finally:
        server.server_close()
    return 0


if __name__ == "__main__":
    sys.exit(main())
